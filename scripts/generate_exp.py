"""Generate a mathematical exp(-x) unit with Q16 input and Q24 output."""
import math
from pathlib import Path

def main():
    out=['// Generated by scripts/generate_exp.py. Mathematical constants, no model data.',
         'module kwt_exp_negative(input wire [32:0] delta,output wire [31:0] result);',
         "    kwt_exp_negative_core core(.clk(1'b0),.delta(delta),.result(result));",
         'endmodule',
         'module kwt_exp_negative_core #(parameter PIPELINE=0)(',
         '    input wire clk,input wire [32:0] delta,output wire [31:0] result',
         ');',
         '    function automatic [24:0] lut(input [8:0] i);', '        begin case(i)']
    for i in range(257):out.append("            9'd%d: lut=25'd%d;"%(i,round(2.**(-i/256)*2**24)))
    out+=['            default:lut=0;','        endcase end','    endfunction',
          "    wire [20:0] scaled=21'((37'(delta[19:0])*37'd94548)>>16);",
          "    wire zero=|delta[32:20];",
          "    if(PIPELINE==0) begin: combinational_exp",
          "    wire [20:0] t=scaled;",
          "    wire [24:0] a=lut({1'b0,t[15:8]}),b=lut({1'b0,t[15:8]}+9'd1);",
          "    wire signed [25:0] diff=$signed({1'b0,b})-$signed({1'b0,a});",
          "    wire signed [34:0] interp=diff*$signed({1'b0,t[7:0]});",
          "    wire [31:0] value=32'($signed({10'd0,a})+(interp>>>8));",
          "    assign result=zero ? 32'd0 : (value>>t[20:16]);",
          "    end else begin: pipelined_exp",
          "        reg [20:0] t;",
          "        reg [24:0] a,b,base;",
          "        reg [7:0] fraction;",
          "        reg [4:0] shift_lut,shift_interp;",
          "        reg [2:0] is_zero;",
          "        reg signed [34:0] interp;",
          "        reg [31:0] value;",
          "        wire signed [25:0] diff=$signed({1'b0,b})-$signed({1'b0,a});",
          "        wire [31:0] adjusted=32'($signed({10'd0,base})+(interp>>>8));",
          "        always @(posedge clk) begin",
          "            t<=scaled;is_zero<={is_zero[1:0],zero};",
          "            a<=lut({1'b0,t[15:8]});b<=lut({1'b0,t[15:8]}+9'd1);",
          "            fraction<=t[7:0];shift_lut<=t[20:16];",
          "            interp<=diff*$signed({1'b0,fraction});base<=a;shift_interp<=shift_lut;",
          "            value<=is_zero[2] ? 32'd0 : (adjusted>>shift_interp);",
          "        end",
          "        assign result=value;",
          "    end",
          "endmodule"]
    (Path(__file__).resolve().parents[1]/'rtl/kwt_exp_negative.sv').write_text('\n'.join(out)+'\n')

if __name__=='__main__':main()
