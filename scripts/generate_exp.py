"""Generate a mathematical exp(-x) unit with Q16 input and Q24 output."""
import math
from pathlib import Path

def main():
    out=['// Generated by scripts/generate_exp.py. Mathematical constants, no model data.',
         'module kwt_exp_negative(input wire [32:0] delta,output wire [31:0] result);',
         '    function automatic [24:0] lut(input [8:0] i);', '        begin case(i)']
    for i in range(257):out.append("            9'd%d: lut=25'd%d;"%(i,round(2.**(-i/256)*2**24)))
    out+=['            default:lut=0;','        endcase end','    endfunction',
          "    wire [33:0] t=34'( (50'(delta)*50'd94548)>>16 );",
          "    wire [24:0] a=lut({1'b0,t[15:8]}),b=lut({1'b0,t[15:8]}+9'd1);",
          "    wire signed [25:0] diff=$signed({1'b0,b})-$signed({1'b0,a});",
          "    wire signed [34:0] interp=diff*$signed({1'b0,t[7:0]});",
          "    wire [31:0] value=32'($signed({10'd0,a})+(interp>>>8));",
          "    assign result=delta>=33'd1048576 ? 32'd0 : (value>>t[33:16]);",'endmodule']
    (Path(__file__).resolve().parents[1]/'rtl/kwt_exp_negative.sv').write_text('\n'.join(out)+'\n')

if __name__=='__main__':main()
