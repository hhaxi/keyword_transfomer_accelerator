"""Generate deterministic synthesizable GELU correction ROM from mathematical constants."""
from pathlib import Path
import sys
ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/'model'))
from ffn_numeric import GELU_TABLE

def main():
    cases='\n'.join("                9'd%d: correction=16'd%d;"%(i,v) for i,v in enumerate(GELU_TABLE))
    text='''// Generated by scripts/generate_gelu.py; fixed mathematical ROM, no task data.
module kwt_gelu(
    input wire signed [39:0] value,
    input wire [4:0] input_shift,output_shift,
    output wire signed [15:0] result,
    output wire saturated
);
    function automatic signed [39:0] round_even(input signed [39:0] v,input [4:0] s);
        reg [39:0] mag,q,rem,half;
        begin
            mag=v[39] ? -v : v;
            q=mag>>s;rem=mag & ((40'd1<<s)-1'b1);
            half=(40'd1<<s)>>1;
            if(s!=0 && (rem>half || (rem==half && q[0]))) q=q+1'b1;
            round_even=v[39] ? -$signed(q) : $signed(q);
        end
    endfunction
    function automatic [15:0] correction(input [8:0] index);
        begin
            case(index)
CASES
                default: correction=0;
            endcase
        end
    endfunction
    wire signed [39:0] z=round_even(value,input_shift);
    wire [39:0] magnitude=z[39] ? -z : z;
    wire [8:0] index={1'b0,magnitude[18:11]};
    wire [15:0] lo=correction(index),hi=correction(index+9'd1);
    wire signed [16:0] delta=$signed({1'b0,hi})-$signed({1'b0,lo});
    wire signed [28:0] product=delta*$signed({1'b0,magnitude[10:0]});
    wire signed [39:0] corr=magnitude>=40'd524288 ? 40'sd0 :
        $signed({24'b0,lo})+($signed({{11{product[28]}},product})>>>11);
    wire signed [39:0] activated=(z[39] ? 40'sd0 : z)-corr;
    wire signed [39:0] scaled=round_even(activated,output_shift);
    assign saturated=scaled>40'sd32767 || scaled< -40'sd32768;
    assign result=scaled>40'sd32767 ? 16'sh7fff :
                  (scaled< -40'sd32768 ? 16'sh8000 : scaled[15:0]);
endmodule
'''.replace('CASES',cases)
    (ROOT/'rtl/kwt_gelu.sv').write_text(text)

if __name__=='__main__':main()
